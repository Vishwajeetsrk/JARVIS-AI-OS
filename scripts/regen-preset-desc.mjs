// Regenerate src/lib/preset-sites.desc.ts from public/preset-sites/*/index.html
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = join(process.cwd(), "public", "preset-sites");

function countFiles(dir) {
  let n = 0;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) n += countFiles(p);
    else n++;
  }
  return n;
}

const entries = [];
for (const e of readdirSync(OUT, { withFileTypes: true })) {
  if (!e.isDirectory()) continue;
  const idx = join(OUT, e.name, "index.html");
  try { statSync(idx); } catch { continue; }
  let fileCount = 0;
  try { fileCount = countFiles(join(OUT, e.name)); } catch {}
  entries.push({
    name: e.name,
    path: `/preset-sites/${e.name}/`,
    hasSource: true,
    fileCount,
  });
}

entries.sort((a, b) => a.name.localeCompare(b.name));

writeFileSync(
  join(process.cwd(), "src", "lib", "preset-sites.desc.ts"),
  `// Auto-generated by scripts/regen-preset-desc.mjs — do not edit by hand.\n` +
  `export interface PresetSite { name: string; path: string; hasSource: boolean; fileCount: number; }\n\n` +
  `export const PRESET_SITES: PresetSite[] = ${JSON.stringify(entries, null, 0)};\n`,
  "utf8"
);

console.log(`preset-sites.desc.ts regenerated with ${entries.length} sites.`);
